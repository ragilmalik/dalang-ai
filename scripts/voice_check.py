"""Strict scan for wording that reads like AI output or like notes to a coding tool.

I want every sentence in this repo to read like I wrote it. slop_check.py gives a rough per-file score; this one
lists every hit with its line number and exits 1 while any are left, so I can loop until it prints zero.

    python scripts/voice_check.py              # scan every tracked and new text file
    python scripts/voice_check.py README.md    # scan only these files
    python scripts/voice_check.py --summary    # counts per file and per rule

What it reads:
- Markdown, text and subtitle files: all prose. Fenced code, inline code and URLs are skipped.
- Python: comments and docstrings. Other string literals are skipped, because the model prompts live there.
- TypeScript and JavaScript: // and /* */ comments, plus any dash character anywhere (UI text included).
- Shell, YAML and TOML: # comments.

Where the word list comes from: Wikipedia's "Signs of AI writing" page (the AI vocabulary section), Pangram's
word study, Pew's 2026 list of AI-typical words, and the humanizer write-ups that build on them. I kept the words
that have a plain swap and dropped the ones I use in a technical sense (for example "landscape video").

A line that has to keep a flagged word (a quoted error message, a product name) can end with the marker
"voice-ok". Use it rarely.
"""
from __future__ import annotations

import argparse
import io
import re
import subprocess
import tokenize
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PROSE_EXT = {".md", ".txt", ".srt", ".vtt"}
HASH_EXT = {".sh", ".yml", ".yaml", ".toml"}
JS_EXT = {".ts", ".tsx", ".js", ".mjs"}
SKIP = {
    "docs/prompts.md",  # generated by the tests from the real model prompts; prompts are meant to be instructions
    "scripts/voice_check.py",  # holds the word lists themselves
    "scripts/slop_check.py",  # same
    "tests/test_voice_check.py",
}
SKIP_PREFIX = ("web/public/fonts/", "web/app/fonts/", "content/fonts/", "LICENSE")  # third-party licence texts

AI_WORDS = [
    r"delv(?:e|es|ed|ing)", r"tapestr(?:y|ies)", r"testament", r"multifaceted", r"realms?", r"interplay",
    r"intricat(?:e|ely)", r"intricacies", r"underscor(?:e|es|ed|ing)", r"leverag(?:e|es|ed|ing)",
    r"elevat(?:e|es|ed|ing)", r"seamless(?:ly)?", r"robust(?:ly|ness)?", r"comprehensive(?:ly)?",
    r"cutting[- ]edge", r"harness(?:es|ed|ing)?", r"game[- ]changer", r"groundbreaking", r"meticulous(?:ly)?",
    r"pivotal", r"crucial(?:ly)?", r"vibrant", r"showcas(?:e|es|ed|ing)", r"bolster(?:s|ed|ing)?",
    r"garner(?:s|ed|ing)?", r"foster(?:s|ed|ing)?", r"embark(?:s|ed|ing)?", r"spearhead(?:s|ed|ing)?",
    r"nuanced", r"additionally", r"furthermore", r"moreover", r"in conclusion", r"in summary", r"to summari[sz]e",
    r"it(?:'s| is) worth noting", r"it(?:'s| is) important to note", r"notably", r"serves as", r"stands as",
    r"plays? an? (?:vital|crucial|key|pivotal|significant|important) role", r"deeply rooted", r"ever[- ]evolving",
    r"(?:digital|evolving|AI|tech|competitive) landscape", r"navigat(?:e|es|ing) the", r"unlock(?:s|ed|ing)?",
    r"empower(?:s|ed|ing|ment)?", r"transformative", r"revolutioni[sz](?:e|es|ed|ing)", r"revolutionary",
    r"state[- ]of[- ]the[- ]art", r"world[- ]class", r"next[- ]level", r"effortless(?:ly)?", r"holistic",
    r"synerg(?:y|ies)", r"paradigm", r"boasts?", r"enhanc(?:e|es|ed|ing|ement|ements)", r"breathtaking",
    r"stunning", r"nestled", r"rich cultural", r"journey", r"magical", r"let's dive", r"dive into", r"deep dive",
    r"here's the thing", r"whether you're", r"i hope this helps", r"elevating", r"align(?:s|ed)? with",
    r"a testament to", r"ensur(?:e|es|ing) that", r"in today's", r"at its core", r"truly", r"indelible",
]
AGENT_WORDS = [
    r"sub-?agents?", r"orchestrat\w*",
    # "agent trace", "agent decision" and "agent loop" are features of the app (the self-checking Meta pipeline),
    # so only an agent that is not one of those is flagged
    r"(?:the|an?) (?:coding |AI )?agents?\b(?! ?(?:trace|decisions?|loop|pipeline|on |:))", r"coding agents?",
    r"next agent", r"future agents?", r"AI agents?", r"the AI\b(?! ?(?:Developer|Hackathon))", r"AI assistant",
    r"assistant", r"\bHark\b", r"Claude", r"ChatGPT", r"GPT-\d", r"coding guide", r"per the guide",
    r"as instructed", r"as requested", r"the user (?:asked|wants|said|requested|told)",
    r"Malik (?:asked|wants|said|told|requested)", r"Malik's (?:guide|rules?|request)", r"\brule \d+\b",
    r"\bround[- ]\d+\b", r"\btask-\d+\b", r"you must", r"make sure to", r"do not forget", r"don't forget",
    r"IMPORTANT:", r"\bNEVER\b", r"\bALWAYS\b", r"\bMUST\b", r"the model (?:should|must)", r"as an AI",
    r"\bprompted\b", r"handoff notes? for", r"for the next (?:session|run|model)",
    r"(?:this|next|scheduled|previous|earlier|last|coding) session", r"\bsandbox\b", r"juicefs", r"/workspace\b",
    r"\bwork/(?:r\d|security|live|wf_demo)", r"the orchestrator",
]
DASH_RE = re.compile(r"[\u2014\u2013]|(?<=\w) -- (?=\w)")


def _rx(words: list[str]) -> re.Pattern[str]:
    return re.compile(r"\b(?:" + "|".join(words) + r")\b", re.I)


AI_RE = _rx(AI_WORDS)
AGENT_RE = re.compile(r"(?:" + "|".join(AGENT_WORDS) + r")")
CASE_SENSITIVE = {r"\bNEVER\b", r"\bALWAYS\b", r"\bMUST\b", r"IMPORTANT:", r"\bHark\b", r"Claude", r"ChatGPT"}
AGENT_CS = re.compile(r"(?:" + "|".join(w for w in AGENT_WORDS if w in CASE_SENSITIVE) + r")")
AGENT_CI = re.compile(r"(?:" + "|".join(rf"\b{w}" if not w.startswith("\\b") else w
                                        for w in AGENT_WORDS if w not in CASE_SENSITIVE) + r")", re.I)


def files_to_scan(args: list[str]) -> list[Path]:
    if args:
        return [Path(a) for a in args]
    out = subprocess.run(["git", "ls-files", "-co", "--exclude-standard"], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout.split("\n")
    keep = []
    for rel in out:
        if not rel or rel in SKIP or rel.startswith(SKIP_PREFIX):
            continue
        p = ROOT / rel
        if p.suffix in PROSE_EXT | HASH_EXT | JS_EXT | {".py"} and p.is_file():
            keep.append(p)
    return sorted(keep)


def prose_lines(text: str) -> list[tuple[int, str]]:
    lines, fenced = [], False
    for n, line in enumerate(text.split("\n"), 1):
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if fenced:
            continue
        line = re.sub(r"`[^`\n]*`", " ", line)
        line = re.sub(r"\]\([^)]*\)", "]", line)
        line = re.sub(r"https?://\S+", " ", line)
        lines.append((n, line))
    return lines


def py_lines(text: str) -> list[tuple[int, str]]:
    """Comments and docstrings only."""
    out: list[tuple[int, str]] = []
    try:
        toks = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return [(n, line) for n, line in enumerate(text.split("\n"), 1) if line.lstrip().startswith("#")]
    prev = tokenize.NEWLINE
    for t in toks:
        if t.type == tokenize.COMMENT:
            out.append((t.start[0], t.string))
        elif t.type == tokenize.STRING and prev in (tokenize.NEWLINE, tokenize.NL, tokenize.INDENT, tokenize.DEDENT,
                                                     tokenize.ENCODING):
            # a bare string statement: a docstring
            for i, part in enumerate(t.string.split("\n")):
                out.append((t.start[0] + i, re.sub(r"`[^`\n]*`", " ", part)))
        if t.type not in (tokenize.COMMENT, tokenize.NL):
            prev = t.type
    return out


def js_lines(text: str) -> list[tuple[int, str]]:
    out: list[tuple[int, str]] = []
    for m in re.finditer(r"/\*.*?\*/|(?<![:\w\\])//[^\n]*", text, re.S):
        start = text.count("\n", 0, m.start()) + 1
        for i, part in enumerate(m.group(0).split("\n")):
            out.append((start + i, re.sub(r"`[^`\n]*`", " ", part)))
    return out


def hash_lines(text: str) -> list[tuple[int, str]]:
    return [(n, line[line.index("#"):]) for n, line in enumerate(text.split("\n"), 1)
            if "#" in line and not line.lstrip().startswith("#!")]


def scan(path: Path) -> list[tuple[int, str, str]]:
    text = path.read_text(encoding="utf-8", errors="replace")
    raw_lines = text.split("\n")
    if path.suffix in PROSE_EXT:
        lines = prose_lines(text)
    elif path.suffix == ".py":
        lines = py_lines(text)
    elif path.suffix in JS_EXT:
        lines = js_lines(text)
    else:
        lines = hash_lines(text)
    hits = []
    for n, line in lines:
        if "voice-ok" in raw_lines[n - 1]:
            continue
        for rx, kind in ((AI_RE, "ai-word"), (AGENT_CI, "agent"), (AGENT_CS, "agent"), (DASH_RE, "dash")):
            for m in rx.finditer(line):
                hits.append((n, kind, m.group(0)))
    if path.suffix in JS_EXT:  # dashes in UI strings are user-facing too
        seen = {n for n, k, _ in hits if k == "dash"}
        for n, line in enumerate(raw_lines, 1):
            if n not in seen and "voice-ok" not in line and DASH_RE.search(line):
                hits.append((n, "dash", DASH_RE.search(line).group(0)))  # type: ignore[union-attr]
    return sorted(set(hits))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="*")
    ap.add_argument("--summary", action="store_true")
    a = ap.parse_args()
    total = 0
    per_file: Counter[str] = Counter()
    per_word: Counter[str] = Counter()
    for p in files_to_scan(a.files):
        rel = p.resolve().relative_to(ROOT) if p.resolve().is_relative_to(ROOT) else p
        for n, kind, word in scan(p):
            total += 1
            per_file[str(rel)] += 1
            per_word[f"{kind}:{word.lower()}"] += 1
            if not a.summary:
                print(f"{rel}:{n}: {kind}: {word}")
    if a.summary:
        for f, c in per_file.most_common():
            print(f"{c:5d}  {f}")
        print("--")
        for w, c in per_word.most_common(60):
            print(f"{c:5d}  {w}")
    print(f"{total} hit(s)")
    return 1 if total else 0


if __name__ == "__main__":
    raise SystemExit(main())
