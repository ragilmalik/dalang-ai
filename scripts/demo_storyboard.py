"""Build the demo video's storyboard and WebVTT captions from the rendered video.

    python scripts/demo_storyboard.py

Reads docs/demo/dalang-ai-demo.mp4, timeline.json, voiceover.txt and dalang-ai-demo.srt.
Writes docs/demo/storyboard/NN-key.jpg (one still per segment), docs/demo/storyboard.jpg (contact sheet),
docs/demo/STORYBOARD.md (time, still, voice-over per shot) and docs/demo/dalang-ai-demo.vtt.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
DEMO = Path(os.environ["DEMO_OUT"]) if os.environ.get("DEMO_OUT") else ROOT / "docs" / "demo"  # same switch as make_demo_video.py
VIDEO = DEMO / "dalang-ai-demo.mp4"


def read_voiceover() -> dict[str, str]:
    text = (DEMO / "voiceover.txt").read_text(encoding="utf-8")
    out: dict[str, str] = {}
    for key, body in re.findall(r"\[(\w+)\]\n(.*?)(?=\n\[\w+\]|\Z)", text, flags=re.S):
        out[key] = " ".join(body.split())
    return out


def srt_to_vtt() -> None:
    srt = (DEMO / "dalang-ai-demo.srt").read_text(encoding="utf-8")
    srt = srt.replace("{\\an8}", "")
    srt = re.sub(r"(\d\d:\d\d:\d\d),(\d\d\d)", r"\1.\2", srt)
    (DEMO / "dalang-ai-demo.vtt").write_text("WEBVTT\n\n" + srt.strip() + "\n", encoding="utf-8")


def fmt(t: float) -> str:
    return f"{int(t // 60)}:{t % 60:04.1f}"


def main() -> None:
    timeline = json.loads((DEMO / "timeline.json").read_text(encoding="utf-8"))
    vo = read_voiceover()
    frames_dir = DEMO / "storyboard"
    frames_dir.mkdir(exist_ok=True)
    for old in frames_dir.glob("*.jpg"):  # shots change between cuts; never leave stale stills behind
        old.unlink()
    rows: list[str] = [
        "# Demo video storyboard",
        "",
        f"Generated by `scripts/demo_storyboard.py` from `dalang-ai-demo.mp4` "
        f"({timeline['total_seconds']:.1f} s). One still per shot, taken mid-shot.",
        "",
        "| # | Time | Shot | Still | Voice-over |",
        "|---|---|---|---|---|",
    ]
    thumbs: list[tuple[str, Path]] = []
    start = 0.0
    for i, seg in enumerate(timeline["segments"], 1):
        key, dur = seg["key"], float(seg["seconds"])
        still = frames_dir / f"{i:02d}-{key}.jpg"
        subprocess.run(
            ["ffmpeg", "-y", "-v", "error", "-ss", f"{start + dur / 2:.2f}", "-i", str(VIDEO),
             "-frames:v", "1", "-vf", "scale=640:-2", "-q:v", "3", str(still)],
            check=True,
        )
        line = vo.get(key) or "(the finished film plays with its own narration and gamelan)"
        rows.append(f"| {i} | {fmt(start)}-{fmt(start + dur)} | {key} | "
                    f"![{key}](storyboard/{still.name}) | {line} |")
        thumbs.append((f"{i}. {key}  {fmt(start)}", still))
        start += dur
    (DEMO / "STORYBOARD.md").write_text("\n".join(rows) + "\n", encoding="utf-8")

    cols, tw, th, pad = 3, 400, 225, 36
    nrows = (len(thumbs) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * tw, nrows * (th + pad)), (20, 14, 10))
    draw = ImageDraw.Draw(sheet)
    font = ImageFont.load_default(size=20)
    for n, (label, path) in enumerate(thumbs):
        x, y = (n % cols) * tw, (n // cols) * (th + pad)
        im = Image.open(path).convert("RGB")
        im.thumbnail((tw - 8, th))
        sheet.paste(im, (x + 4, y))
        draw.text((x + 8, y + th + 6), label, fill=(240, 200, 120), font=font)
    sheet.save(DEMO / "storyboard.jpg", quality=88)
    srt_to_vtt()
    print(f"storyboard: {len(thumbs)} shots, {timeline['total_seconds']:.1f} s")


if __name__ == "__main__":
    main()
